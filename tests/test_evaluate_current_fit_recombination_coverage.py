def _capture(identifier, *, old, new, shard=0, fallback=None):
    ranked = bool(old)
    return {"id": identifier, "component_id": "component-" + identifier,
            "request": {"input": "roman-" + identifier, "context": ""},
            "source_reference": {"ranked": ranked, "pool_rows": len(old),
                                 "source_shard": shard},
            "status": "generated" if ranked else "no_pool",
            "proposals": [{"text": text} for text in new],
            "fallback_public": fallback if not ranked else None}


def _feature(identifier, *, old, expected, shard=0, public=None):
    return {"id": identifier, "component_id": "component-" + identifier,
            "input": "roman-" + identifier, "candidates": old,
            "expected": expected, "ranked": bool(old), "source_shard": shard,
            "public_candidates": public or ["roman-" + identifier]}


def test_late_label_summary_separates_reachable_search_misses(tmp_path, monkeypatch):
    captures, features, audit = [], [], []
    # 1,559 already-covered ranked rows.
    for index in range(1559):
        identifier = f"covered-{index}"
        captures.append(_capture(identifier, old=["gold"], new=[]))
        features.append(_feature(identifier, old=["gold"], expected=["gold"]))
    # 70 ranked misses: 38 reachable, only ten generated by the bounded search.
    for index in range(70):
        identifier = f"missing-{index}"
        generated = index < 10
        captures.append(_capture(identifier, old=["wrong"], new=["gold"] if generated else []))
        features.append(_feature(identifier, old=["wrong"], expected=["gold"]))
        audit.append({"id": identifier, "reachable": index < 38})
    # Thirteen no-pool rows remain in a separate denominator.
    for index in range(13):
        identifier = f"no-pool-{index}"
        fallback = [{"text": "roman-" + identifier}]
        captures.append(_capture(identifier, old=[], new=[], fallback=fallback))
        features.append(_feature(identifier, old=[], expected=["unseen"], public=[fallback[0]["text"]]))
    reachability = {"schema": "current-fit-edge-reachability-v1",
                    "features_sha256": target.FEATURES_SHA256,
                    "counts": {"missing_gold_rows": 70, "reachable": 38, "unreachable": 32},
                    "rows": audit}
    output = tmp_path / "rows.jsonl"
    with output.open("w", encoding="utf-8") as stream:
        summary, ids = target.evaluate_rows(iter(captures), iter(features), reachability, stream)
    assert len(ids) == 1642
    assert summary["old_pool_covered"] == 1559
    assert summary["newly_covered"] == summary["newly_covered_reachable"] == 10
    assert summary["reachable_but_not_generated"] == 28
    assert summary["audit_unreachable"] == 32
    assert summary["no_pool_rows"] == 13
    assert "top1" not in summary


def test_rejects_generated_gold_marked_unreachable(tmp_path):
    captures, features = [], []
    for index in range(1559):
        identifier = f"covered-{index}"
        captures.append(_capture(identifier, old=["gold"], new=[]))
        features.append(_feature(identifier, old=["gold"], expected=["gold"]))
    audit = []
    for index in range(70):
        identifier = f"missing-{index}"
        captures.append(_capture(identifier, old=["wrong"],
                                 new=["gold"] if index == 40 else []))
        features.append(_feature(identifier, old=["wrong"], expected=["gold"]))
        audit.append({"id": identifier, "reachable": index < 38})
    for index in range(13):
        identifier = f"no-pool-{index}"
        fallback = [{"text": "roman-" + identifier}]
        captures.append(_capture(identifier, old=[], new=[], fallback=fallback))
        features.append(_feature(identifier, old=[], expected=["unseen"],
                                 public=[fallback[0]["text"]]))
    reachability = {"schema": "current-fit-edge-reachability-v1",
                    "features_sha256": target.FEATURES_SHA256,
                    "counts": {"missing_gold_rows": 70, "reachable": 38, "unreachable": 32},
                    "rows": audit}
    with (tmp_path / "rows").open("w", encoding="utf-8") as stream:
        with pytest.raises(ValueError, match="contradicts reachability audit"):
            target.evaluate_rows(iter(captures), iter(features), reachability, stream)


class _Guard:
    def __init__(self, *args, **kwargs):
        pass

    def __enter__(self):
        return self

    def __exit__(self, *args):
        return False

    class _Operation:
        def __enter__(self):
            return None

        def __exit__(self, *args):
            return False

    def operation(self, *args, **kwargs):
        return self._Operation()

    def sample_and_append(self, stage):
        return {"stage": stage}


def _sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def test_missing_independent_proof_fails_before_fit_label_reader(tmp_path, monkeypatch):
    fixed = {}
    for name in ("producer", "verifier", "probe_verifier", "base_verifier",
                 "prepared", "helper", "resources"):
        path = tmp_path / name
        path.write_text(name, encoding="utf-8")
        fixed[name] = path
    monkeypatch.setattr(target, "PRODUCER", fixed["producer"])
    monkeypatch.setattr(target, "VERIFIER", fixed["verifier"])
    monkeypatch.setattr(target, "PROBE_VERIFIER", fixed["probe_verifier"])
    monkeypatch.setattr(target, "BASE_VERIFIER", fixed["base_verifier"])
    monkeypatch.setattr(target, "PREPARED", fixed["prepared"])
    monkeypatch.setattr(target, "HELPER", fixed["helper"])
    monkeypatch.setattr(target, "RESOURCE_HELPER", fixed["resources"])
    monkeypatch.setattr(target, "system_swap_bytes", lambda: 0)
    monkeypatch.setattr(target, "PRODUCER_SHA256", _sha(fixed["producer"]))
    monkeypatch.setattr(target, "PROBE_VERIFIER_SHA256", _sha(fixed["probe_verifier"]))
    monkeypatch.setattr(target, "BASE_VERIFIER_SHA256", _sha(fixed["base_verifier"]))
    monkeypatch.setattr(target, "PREPARED_SHA256", _sha(fixed["prepared"]))
    monkeypatch.setattr(target, "HELPER_SHA256", _sha(fixed["helper"]))
    monkeypatch.setattr(target, "RESOURCE_HELPER_SHA256", _sha(fixed["resources"]))

    probe = tmp_path / "probe"
    probe.mkdir()
    hashes = {}
    for name in target.NAMES:
        if name == "independent-verification.json":
            hashes[name] = "0" * 64
            continue
        path = probe / name
        path.write_text("{}\n", encoding="utf-8")
        hashes[name] = _sha(path)
    manifest = tmp_path / "manifest.json"
    manifest.write_text(json.dumps({
        "schema": "current-fit-recombination-coverage-intake-v1",
        "producer_sha256": _sha(fixed["producer"]),
        "verifier_sha256": _sha(fixed["verifier"]),
        "probe": {"directory": str(probe), "hashes": hashes},
        "shards": []}), encoding="utf-8")
    opened = []

    def label_reader(path):
        opened.append(path)
        raise AssertionError("FIT label reader must not be called")

    with pytest.raises(ValueError, match="independent-verification.json hash differs"):
        target.run(tmp_path / "output", manifest, label_reader=label_reader,
                   watchdog_cls=_Guard)
    assert opened == []
    assert (tmp_path / "output/failure.json").is_file()


